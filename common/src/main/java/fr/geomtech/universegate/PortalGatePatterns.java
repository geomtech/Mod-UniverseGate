    /** Gris du motif du cadre au pixel (x, y), y vers le haut. */
    static int frame(int x, int y) {
        return FRAME[(15 - Math.floorMod(y, 16)) * 16 + Math.floorMod(x, 16)];
    }

    static int core(int x, int y) {
        return CORE[(15 - Math.floorMod(y, 16)) * 16 + Math.floorMod(x, 16)];
    }

    static int gray(int g) {
        return (g << 16) | (g << 8) | g;
    }

    static long hash(long a, long b, long c) {
        long h = a * 0x9E3779B97F4A7C15L ^ b * 0xC2B2AE3D27D4EB4FL ^ c * 0x165667B19E3779F9L;
        h ^= (h >>> 29);
        h *= 0xBF58476D1CE4E5B9L;
        h ^= (h >>> 32);
        return h & Long.MAX_VALUE;
    }
